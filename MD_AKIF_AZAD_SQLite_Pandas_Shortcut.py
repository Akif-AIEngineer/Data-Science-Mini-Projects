# Step 1: Tools On Karna ...
import sqlite3
import pandas as pd
# Step 2: PYHTON (Waiter) Ko SQL (Kitchen) Se Jodna ...
conn = sqlite3.connect('Akif_annu.db')
# Step 2: Order Likhne Ke Liye Pen (Cursor) But DATA Chota Hai To Shortcut Use (execute) Karna + TABLE Bana Na ...
conn.execute("CREATE TABLE IF NOT EXISTS Students (Roll_Number INTEGER, Name TEXT)")
# Step 3: TABLE Mein Value Daalna ...
conn.execute("INSERT INTO Students VALUES (1, 'MD AKIF AZAD')")
# Step 4: DATA Ko Lock Karnaa Taaki DATA Save Ho Jaaye Light Cut Hone Par Bhi DATA Na Ude ...
conn.commit()
# Step 5: DATA Ko TABLE Mein Mast Sajana PANDAS Ki Help Se ...
df = pd.read_sql("SELECT * FROM Students", conn)
# Step 6: FINAL Data Ko Chamchamata Dekhna ...
print(df)