# Step 1: Ninja (WEB SCRAPING) Ko Bulao Aur Saath Jhadu (BEAUTIFULSOUP) Ko Bulao = Tools On Karna ...
import requests
from bs4 import BeautifulSoup
# Step 2: Ninja (WEB SCRAPING) Ko DATA Laane Ke Liye Bhejo Website Se Aur Saath Ek VIP CARD Banao Taaki Wikipedia Ko Lage Tum CHROME Browser Se Aayee Hoo ...
headers = { 'User-Agent': 'Mozilla/5.0' }
ninja_data = requests.get("https://en.wikipedia.org/wiki/Python_(programming_language)", headers = headers).text
# Step 3: BEAUTIFULSOUP Ki Help Se DATA Ko Saaf Karo ...
soup = BeautifulSoup(ninja_data, 'html.parser')
# Step 4: DATA Se Khazana Nikalna ( Safety LOCK Ke Saath) ...
Khazana = soup.find('h1')
# Step 5: Final Safety Check Kar Ke Khazana De Do ... 
if Khazana != None:
	print ("Main Heading:", Khazana.text)
else:
	print ("Bhai Main Heading Nhi Hai !")